#!/bin/bash
# Один прогон дашборда: выгрузка из WB → свод → готовая страница.
# Токены берутся из .env рядом и никуда больше не попадают.
#
#   bash run.sh          полный прогон: всё окно, финотчёт, воронка, возвраты
#   bash run.sh fast     быстрый: свежий хвост заказов, сборка, отгрузка, остатки
#
# Быстрый прогон нужен днём: пороги комиссии WB считаются в часах, и очередь
# сборки надо видеть сейчас, а не завтра. Ставки и выкуп за час не меняются.
set -e
cd "$(dirname "$0")"
[ -f .env ] && set -a && . ./.env && set +a
export WB_FIN_MAX_AGE_H="${WB_FIN_MAX_AGE_H:-20}"
[ "$1" = "fast" ] && export FAST=1

python3 collect.py
python3 collect_extra.py || true   # если остатки или воронка недоступны, страница соберётся без них
python3 aggregate.py
python3 render.py
echo "СТРАНИЦА: $(pwd)/dist/index.html"
